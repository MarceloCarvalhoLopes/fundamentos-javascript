//1 - Utilize if/else para escrever um código que retorne o maior de dois números. Defina, no começo do seu código, duas variáveis com os valores que serão comparados

const valor1 = 600;
const valor2 = 600;

if (valor1 > valor2) {
  console.log(`O valor1 é maior -> ${valor1}`);
} else if (valor1 < valor2) {
  console.log(`O valor2 é o maior -> ${valor2}`);
} else {
  console.log(`Os valores são iguais -> ${valor1} - ${valor2}`);
}
